// 批 A2 契约(2026-11-18 巡检单 kode-ruff-format-statusbar.md):pyproject.toml
// [tool.ruff] 检测与引导。五钉子:
// ①无配置 → 确认后生成最小 pyproject.toml([project] 名占位推断 + [tool.ruff]
//   line-length=88 + 生成标注 + 常用值注释)
// ②已有 pyproject 无段 → 确认后安全追加(原内容逐字节保留,只补 [tool.ruff])
// ③已有 [tool.ruff]/ruff.toml → 不动(零写零弹窗)
// ④用户拒绝 → 会话内不重复问(第二次 ensure 直接短路,无弹窗)
// ⑤设置关闭 → 完全不生成(零读零写零弹窗)
// 附加钉:追加守卫(多行字符串未闭/尾行数组未闭/[tool] 下内联 ruff 键 →
// 如实 unsafe 跳过不写);根名不可安全推断时省略 [project] 段。
import { describe, expect, it, vi } from 'vitest';
import {
  appendToolRuffSection,
  buildCreateContent,
  createRuffConfigEnsureSession,
  hasToolRuffSection,
  type RuffConfigEnsureDeps
} from '../src/backend/ruffConfigEnsure';

interface Depot {
  files: Map<string, string>;
  dialogs: Array<{ message: string; items: string[] }>;
  answer: string | undefined;
  enabled: boolean;
  root: string | null;
}

const makeDeps = (over: Partial<Depot> = {}): { deps: RuffConfigEnsureDeps; depot: Depot } => {
  const depot: Depot = {
    files: new Map<string, string>(over.files ?? []),
    dialogs: [],
    answer: over.answer,
    enabled: over.enabled ?? true,
    root: over.root === undefined ? '/w/proj' : over.root
  };
  const deps: RuffConfigEnsureDeps = {
    getSettingEnabled: () => depot.enabled,
    workspaceRoot: () => depot.root,
    rootFileExists: name => depot.files.has(name),
    readFileText: name => depot.files.get(name) ?? null,
    writeFileText: (name, content) => {
      depot.files.set(name, content);
      return true;
    },
    showInformationMessage: (message, ...items) => {
      depot.dialogs.push({ message, items });
      return Promise.resolve(depot.answer);
    }
  };
  return { deps, depot };
};

const CREATE_ACTION = 'Create';

describe('纯函数面', () => {
  it('hasToolRuffSection:识别 [tool.ruff]/[tool.ruff.sub]/带注释行,不认注释伪装与 [tool]', () => {
    expect(hasToolRuffSection('[tool.ruff]\nline-length = 88\n')).toBe(true);
    expect(hasToolRuffSection('[tool.ruff.lint]\nselect = []\n')).toBe(true);
    expect(hasToolRuffSection('[tool]\nruff = { line-length = 100 }\n')).toBe(false);
    expect(hasToolRuffSection('# [tool.ruff] comment only\n')).toBe(false);
    expect(hasToolRuffSection('x = "[tool.ruff]"\n')).toBe(false);
  });

  it('buildCreateContent:line-length=88 + 生成标注 + 常用值注释;名可推断带 [project]', () => {
    const content = buildCreateContent('my-proj');
    expect(content).toContain('[tool.ruff]');
    expect(content).toContain('line-length = 88');
    expect(content).toContain('name = "my-proj"');
    expect(content).toContain('79 / 100 / 120');
    // 生成标注(Kode 生成,可自由修改)
    expect(content).toMatch(/Kode.*生成|Generated by Kode/);
    // 名不可安全推断 → 省略 [project] 段(pyproject 仅 [tool.ruff] 合法)
    expect(buildCreateContent(null)).not.toContain('[project]');
  });

  it('appendToolRuffSection:原内容逐字节保留,只追加 [tool.ruff] 段', () => {
    const original = '[project]\nname = "demo"\n';
    const appended = appendToolRuffSection(original);
    expect(appended).not.toBeNull();
    expect(appended!.startsWith(original)).toBe(true);
    expect(hasToolRuffSection(appended!)).toBe(true);
    // 已有段 → null(不动)
    expect(appendToolRuffSection('[tool.ruff]\nline-length = 100\n')).toBeNull();
  });

  it('追加守卫:多行字符串未闭/尾行数组未闭/[tool] 内联 ruff 键 → null 如实拒绝', () => {
    expect(appendToolRuffSection('x = """\nunclosed\n')).toBeNull();
    expect(appendToolRuffSection('deps = [\n  "a",\n')).toBeNull();
    expect(appendToolRuffSection('[tool]\nruff = { line-length = 100 }\n')).toBeNull();
    // 正常多行数组已闭合 → 可追加
    expect(appendToolRuffSection('deps = [\n  "a",\n]\n')).not.toBeNull();
  });
});

describe('会话编排五钉子', () => {
  it('① 无配置 → 确认后生成最小文件;内容可预览', async () => {
    const { deps, depot } = makeDeps({ answer: CREATE_ACTION });
    const session = createRuffConfigEnsureSession();
    const outcome = await session.ensure(deps);
    expect(outcome).toBe('created');
    expect(depot.files.has('pyproject.toml')).toBe(true);
    const written = depot.files.get('pyproject.toml')!;
    expect(written).toContain('[tool.ruff]');
    expect(written).toContain('line-length = 88');
    // 弹窗带内容预览
    expect(depot.dialogs).toHaveLength(1);
    expect(depot.dialogs[0].message).toContain('[tool.ruff]');
    expect(depot.dialogs[0].items.length).toBeGreaterThanOrEqual(2);
  });

  it('② 已有 pyproject 无段 → 确认后安全追加,原内容前缀逐字节不动', async () => {
    const original = '[project]\nname = "demo"\nversion = "0.1.0"\n';
    const { deps, depot } = makeDeps({ files: [['pyproject.toml', original]], answer: CREATE_ACTION });
    const session = createRuffConfigEnsureSession();
    const outcome = await session.ensure(deps);
    expect(outcome).toBe('appended');
    const written = depot.files.get('pyproject.toml')!;
    expect(written.startsWith(original)).toBe(true);
    expect(hasToolRuffSection(written)).toBe(true);
  });

  it('③ 已有 [tool.ruff] 或 ruff.toml → not-needed,零弹窗零写', async () => {
    for (const files of [
      [['pyproject.toml', '[tool.ruff]\nline-length = 120\n']],
      [['ruff.toml', 'line-length = 120\n']]
    ] as Array<Array<[string, string]>>) {
      const { deps, depot } = makeDeps({ files });
      const session = createRuffConfigEnsureSession();
      expect(await session.ensure(deps)).toBe('not-needed');
      expect(depot.dialogs).toHaveLength(0);
    }
  });

  it('④ 拒绝 → declined;会话内第二次 ensure 直接 declined-session,不再弹窗', async () => {
    const { deps, depot } = makeDeps({ answer: 'Not now' });
    const session = createRuffConfigEnsureSession();
    expect(await session.ensure(deps)).toBe('declined');
    expect(depot.dialogs).toHaveLength(1);
    expect(await session.ensure(deps)).toBe('declined-session');
    expect(depot.dialogs).toHaveLength(1);
    expect(depot.files.has('pyproject.toml')).toBe(false);
  });

  it('⑤ 设置关闭 → setting-off,零读零写零弹窗;无根 → no-root', async () => {
    const off = makeDeps({ enabled: false });
    const sessionOff = createRuffConfigEnsureSession();
    expect(await sessionOff.ensure(off.deps)).toBe('setting-off');
    expect(off.depot.dialogs).toHaveLength(0);
    const noRoot = makeDeps({ root: null });
    expect(await createRuffConfigEnsureSession().ensure(noRoot.deps)).toBe('no-root');
  });

  it('unsafe 追加 → 如实跳过不弹窗不写;修好文件后同会话可再试', async () => {
    const original = 'deps = [\n  "a",\n';
    const { deps, depot } = makeDeps({ files: [['pyproject.toml', original]], answer: CREATE_ACTION });
    const session = createRuffConfigEnsureSession();
    expect(await session.ensure(deps)).toBe('unsafe-append');
    expect(depot.dialogs).toHaveLength(0);
    // 用户补完括号 → 同会话重试成功
    depot.files.set('pyproject.toml', 'deps = [\n  "a",\n]\n');
    expect(await session.ensure(deps)).toBe('appended');
  });

  it('已就绪(not-needed)后同会话再 ensure → 直接 not-needed 不重复检测', async () => {
    const { deps, depot } = makeDeps({ files: [['ruff.toml', 'line-length = 79\n']] });
    const session = createRuffConfigEnsureSession();
    expect(await session.ensure(deps)).toBe('not-needed');
    depot.files.delete('ruff.toml');
    expect(await session.ensure(deps)).toBe('not-needed');
    expect(depot.dialogs).toHaveLength(0);
  });
});
