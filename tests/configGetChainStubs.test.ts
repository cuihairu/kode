// CFG-GETCHAIN-003 声明式 config.get* stub 纯核契约:
//   - 声明解析:合法多管理器/坏形状逐条跳过不抛(键名非标识符、类型含
//     引号换行、keys 空、容器非对象)
//   - stub 生成:逐键 get/__getitem__ @overload(Literal 集合完整性)、
//     object 兜底、直属属性注解、另产 @dataclass 属性式类、管理器绑定、
//     source 头注释;空声明不引 dataclasses
//   - 落盘/接线面被 PYLANCE-CRASH-001 门禁挡,本批只有纯函数(零 IO)
// 期望文本与生成器逐字对账(直读非手抄快照)。
import { describe, expect, it } from 'vitest';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import * as fs from 'node:fs';
import * as os from 'node:os';
import * as path from 'node:path';
import {
  generateConfigGetChainStubPyi,
  parseConfigGetChainDeclarations
} from '../src/backend/configGetChainStubs';

const DECL_RAW = {
  config: {
    keys: { hp: 'int', name: 'str', skills: 'list[str]' },
    source: 'configs/skills.xlsx'
  },
  reward: { keys: { gold: 'int' } }
};

describe('parseConfigGetChainDeclarations(声明解析,容错面宽)', () => {
  it('合法声明:管理器序保持、键序保持、source 可选', () => {
    const decls = parseConfigGetChainDeclarations(DECL_RAW);
    expect(decls.map(d => d.manager)).toEqual(['config', 'reward']);
    expect(decls[0].keys).toEqual([
      { key: 'hp', type: 'int' },
      { key: 'name', type: 'str' },
      { key: 'skills', type: 'list[str]' }
    ]);
    expect(decls[0].source).toBe('configs/skills.xlsx');
    expect(decls[1].source).toBeUndefined();
  });

  it('坏形状逐条跳过:非标识符管理器/键、类型含引号换行反斜杠、keys 空/缺/非对象;容器非对象=空表', () => {
    const decls = parseConfigGetChainDeclarations({
      '2bad': { keys: { a: 'int' } },
      ok: { keys: { a: 'int' }, junk: 1 },
      'no-keys': {},
      'empty-keys': { keys: {} },
      'all-bad-keys': { keys: { 'b-dash': 'int', good: 'has "quote"' } },
      'bad-body': 'str'
    });
    expect(decls.map(d => d.manager)).toEqual(['ok']);
    expect(decls[0].keys).toEqual([{ key: 'a', type: 'int' }]);
    expect(parseConfigGetChainDeclarations('nope')).toEqual([]);
    expect(parseConfigGetChainDeclarations(null)).toEqual([]);
  });
});

describe('generateConfigGetChainStubPyi(stub 文本生成)', () => {
  const decls = parseConfigGetChainDeclarations(DECL_RAW);
  const pyi = generateConfigGetChainStubPyi(decls);

  it('逐键 get/__getitem__ @overload+Literal 集合完整;object 兜底;直属属性;管理器绑定;source 头注释', () => {
    expect(pyi).toContain('# Generated by kode from kbengine.configData declarations. Do not edit.');
    expect(pyi).toContain('# source: configs/skills.xlsx');
    expect(pyi).toContain('from typing import Literal, overload');
    // get 重载:每键一行,Literal 集合完整
    for (const line of [
      'def get(self, key: Literal["hp"]) -> int: ...',
      'def get(self, key: Literal["name"]) -> str: ...',
      'def get(self, key: Literal["skills"]) -> list[str]: ...',
      'def get(self, key: str) -> object: ...'
    ]) {
      expect(pyi).toContain(line);
    }
    // __getitem__ 同套重载
    expect(pyi).toContain('def __getitem__(self, key: Literal["gold"]) -> int: ...');
    expect(pyi).toContain('def __getitem__(self, key: str) -> object: ...');
    // 直属属性注解 + 管理器绑定(表类名带管理器后缀防撞)
    expect(pyi).toContain('    hp: int');
    expect(pyi).toContain('    skills: list[str]');
    expect(pyi).toContain('config: _KodeConfigTable_config');
    expect(pyi).toContain('reward: _KodeConfigTable_reward');
    // dataclass 臂:每管理器另产纯注解属性类(键序=声明序);绑定仍指表类
    expect(pyi).toContain('from dataclasses import dataclass');
    expect(pyi).toContain(
      '@dataclass\nclass _KodeConfigData_config:\n    hp: int\n    name: str\n    skills: list[str]'
    );
    expect(pyi).toContain('@dataclass\nclass _KodeConfigData_reward:\n    gold: int');
    expect(pyi).not.toContain('config: _KodeConfigData_config');
  });

  it('空声明 → 仅头与 import(零类零绑定,不引 dataclasses)', () => {
    const empty = generateConfigGetChainStubPyi([]);
    expect(empty).toContain('from typing import Literal, overload');
    expect(empty).not.toContain('class ');
    expect(empty).not.toContain('dataclass');
    expect(empty).not.toMatch(/^config:/m);
  });

  it('生成物 Python 语法有效:python3 py_compile 实测(entityWizard python3 先例)', async () => {
    const run = promisify(execFile);
    const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'kode-cfgstub-')), 'config_gen.pyi');
    fs.writeFileSync(file, pyi, 'utf8');
    try {
      await run('python3', ['-m', 'py_compile', file]);
    } finally {
      fs.rmSync(path.dirname(file), { recursive: true, force: true });
    }
  });
});
