/**
 * CFG-GETCHAIN-003 声明式 config.get* 类型补全——纯核(零 IO/零写盘):
 * 用户工程无 Excel 大字面量模块,用法是 `config.getXXX()`/`config[k]` 风格,
 * 运行时是 dict 静态推断无解——提示不靠推断靠**声明**:工作区声明
 * 「管理器对象 → 表键集合(键→类型)」,kode 生成 .pyi stub(Literal 重载
 * get/__getitem__/直属属性三用),Pylance 原生吃。
 *
 * 本模块=声明解析+stub 文本生成(可测纯函数)。**落盘/接线面被
 * PYLANCE-CRASH-001 取证门禁挡**(任务书纪律:排除 kode 写盘触发 Pylance
 * 崩溃的嫌疑之前,不往 stubPath 写新东西)——接线随该批放行后单开。
 */

export interface ConfigGetChainKey {
  key: string;
  /** Python 注解文本(声明原样,如 `int`/`list[str]`) */
  type: string;
}

export interface ConfigGetChainDeclaration {
  /** 管理器对象名(Python 标识符;stub 尾部以其为名出绑定) */
  manager: string;
  /** 键→类型(保持声明序;Literal 集合与属性注解同源) */
  keys: ConfigGetChainKey[];
  /** 可选来源表路径(进 stub 头注释,溯源用) */
  source?: string;
}

const IDENT = /^[A-Za-z_]\w*$/;

/**
 * 解析设置声明(`{ "config": { "keys": { "hp": "int" }, "source": "…" } }`)
 * → 逐管理器声明表。坏形状逐条跳过不抛(设置是用户手写 JSON,容错面宽):
 * 非对象/管理器名非标识符/keys 缺失或空/键名非标识符/类型文本含控制字符
 * 或引号(stub 文本安全)——整条弃,其余照收。
 */
export function parseConfigGetChainDeclarations(raw: unknown): ConfigGetChainDeclaration[] {
  if (typeof raw !== 'object' || raw === null) {
    return [];
  }
  const out: ConfigGetChainDeclaration[] = [];
  for (const [manager, body] of Object.entries(raw as Record<string, unknown>)) {
    if (!IDENT.test(manager) || typeof body !== 'object' || body === null) {
      continue;
    }
    const { keys, source } = body as { keys?: unknown; source?: unknown };
    if (typeof keys !== 'object' || keys === null) {
      continue;
    }
    const parsedKeys: ConfigGetChainKey[] = [];
    for (const [key, type] of Object.entries(keys as Record<string, unknown>)) {
      if (!IDENT.test(key) || typeof type !== 'string') {
        continue;
      }
      const trimmed = type.trim();
      // stub 文本安全:类型注解不含换行/引号/反斜杠(其余注解字符放行)
      if (!trimmed || /[\n\r'"\\]/.test(trimmed)) {
        continue;
      }
      parsedKeys.push({ key, type: trimmed });
    }
    if (parsedKeys.length === 0) {
      continue;
    }
    const decl: ConfigGetChainDeclaration = { manager, keys: parsedKeys };
    if (typeof source === 'string' && source.trim()) {
      decl.source = source.trim();
    }
    out.push(decl);
  }
  return out;
}

/**
 * 生成 stub 文本(`config_gen.pyi` 形态):每管理器一个表类,
 * `get(key: Literal[...])` 逐键 @overload + `object` 兜底、
 * `__getitem__` 同套重载、直属属性注解(dict/属性/get 三用),
 * 尾部以管理器名出模块级绑定。
 */
export function generateConfigGetChainStubPyi(declarations: readonly ConfigGetChainDeclaration[]): string {
  const header = [
    '# Generated by kode from kbengine.configData declarations. Do not edit.',
    ...declarations.filter(d => d.source).map(d => `# source: ${d.source}`)
  ];
  const body: string[] = [];
  for (const decl of declarations) {
    const cls = `_KodeConfigTable_${decl.manager}`;
    body.push(`class ${cls}:`);
    for (const { key, type } of decl.keys) {
      body.push(`    @overload`);
      body.push(`    def get(self, key: Literal["${key}"]) -> ${type}: ...`);
    }
    body.push(`    def get(self, key: str) -> object: ...`);
    body.push('');
    for (const { key, type } of decl.keys) {
      body.push(`    @overload`);
      body.push(`    def __getitem__(self, key: Literal["${key}"]) -> ${type}: ...`);
    }
    body.push(`    def __getitem__(self, key: str) -> object: ...`);
    body.push('');
    for (const { key, type } of decl.keys) {
      body.push(`    ${key}: ${type}`);
    }
    body.push('');
    body.push(`${decl.manager}: ${cls}`);
    body.push('');
  }
  return [
    ...header,
    '',
    'from typing import Literal, overload',
    '',
    body.join('\n').trimEnd() + '\n'
  ].join('\n');
}
