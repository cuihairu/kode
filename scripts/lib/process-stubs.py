def declarations(module):
    return [copy.deepcopy(n) for n in ast.parse((PACKAGE / module).read_text()).body
            if isinstance(n, (ast.FunctionDef, ast.Assign, ast.AnnAssign))
            and '__getattr__' not in names([n])]


common_module = declarations('_KBEngine_common.pyi')
python_module = declarations('_KBEngine_pythonapp.pyi')
RESOURCE = {'publish', 'scriptLogType', 'getResFullPath', 'hasRes', 'open', 'listPathRes', 'matchPath',
            'debugTracing', 'genUUID64', 'urlopen', 'component',
            'LOG_TYPE_NORMAL', 'LOG_TYPE_INFO', 'LOG_TYPE_ERR', 'LOG_TYPE_DBG', 'LOG_TYPE_WAR'}
