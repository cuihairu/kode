def parse(source):
    return ast.parse(source).body


def text(nodes):
    return ast.unparse(ast.fix_missing_locations(ast.Module(body=nodes, type_ignores=[]))) + '\n'


def cls(name, module=None):
    return copy.deepcopy(next(n for n in ast.parse((PACKAGE / (module or name + '.pyi')).read_text()).body
                              if isinstance(n, ast.ClassDef) and n.name == name))


def names(nodes):
    result = set()
    for n in nodes:
        if isinstance(n, (ast.ClassDef, ast.FunctionDef)):
            result.add(n.name)
        elif isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name):
            result.add(n.target.id)
        elif isinstance(n, ast.Assign):
            result.update(t.id for t in n.targets if isinstance(t, ast.Name))
    return result


def select_class(c, allowed):
    c.body = [n for n in c.body if names([n]) & set(allowed)] or [ast.Pass()]
    return c


def replace_member(c, name, source):
    c.body = [n for n in c.body if name not in names([n])] + parse(source)


def write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEADER + content.rstrip() + "\n")


