impl HoverEngine {
    /// LSP entry: UTF-16 position -> decide the face -> the item set. An
    /// undecidable context returns None
    /// (the server answers with a null result, no error and no blocking).
    pub fn completion(
        &self,
        key: &DocumentKey,
        text: &str,
        line0: u32,
        character: u32,
    ) -> Option<CompletionResponse> {
        if key.uri.as_path().ends_with(".py") {
            let prefix = line_prefix(text, line0, character as usize)?;
            if let Some(report) =
                crate::python_process::completion(key.uri.as_path(), text, &prefix)
            {
                return Some(report);
            }
            return self.python_self_completion(key, &prefix);
        }
        if matches!(file_kind_of_uri(&key.uri), FileKind::Other) {
            return None;
        }
        let col = char_col_of(text, line0, character)?;
        self.complete_at(key, text, line0, col)
    }

    /// The face decision + item-set body (col = the in-line char column, 0-based).
    fn complete_at(
        &self,
        key: &DocumentKey,
        text: &str,
        line0: u32,
        col: usize,
    ) -> Option<CompletionResponse> {
        let path = key.uri.as_path();
        let prefix = line_prefix(text, line0, col)?;
        let (head, fragment, open_tag) = split_fragment(&prefix);
        if open_tag {
            // Open-tag context: the top of the tag stack above the cursor decides the item set.
            let stack = tag_stack(&lines_above(text, line0));
            let top = stack.last()?;
            match file_kind_of_uri(&key.uri) {
                FileKind::Def => match top.as_str() {
                    "Properties" => {
                        let entity = def_entity_name(path)?;
                        let def = parse_def(text);
                        Some(self.members_response(
                            "openTag",
                            "Properties",
                            None,
                            path,
                            &entity,
                            &fragment,
                            &def,
                        ))
                    }
                    "BaseMethods" | "CellMethods" | "ClientMethods" => {
                        let entity = def_entity_name(path)?;
                        let facet = facet_of_section(top);
                        let def = parse_def(text);
                        Some(self.members_response(
                            "openTag",
                            facet_section_of(facet),
                            Some(facet),
                            path,
                            &entity,
                            &fragment,
                            &def,
                        ))
                    }
                    "Components" => {
                        Some(self.entities_response(key, "openTag", "Components", &fragment))
                    }
                    _ => None,
                },
                FileKind::Entities if top == "root" => {
                    Some(self.entities_response(key, "openTag", "Entities", &fragment))
                }
                _ => None,
            }
        } else {
            // Value context: the line prefix is `<Tag>` followed by (whitespace) + a
            // fragment; the fragment has been stripped, and what remains after the
            // tag must be pure whitespace, otherwise this is not a value position.
            let trimmed = head.trim_start();
            let (section, kind_ctx) = if let Some(rest) = trimmed.strip_prefix("<Parent>") {
                if !rest.chars().all(char::is_whitespace) {
                    return None;
                }
                ("Entity", "entity")
            } else if let Some((tag, rest)) = ["<Type>", "<Arg>", "<of>"]
                .iter()
                .find_map(|tag| trimmed.strip_prefix(tag).map(|rest| (*tag, rest)))
            {
                if !rest.chars().all(char::is_whitespace) {
                    return None;
                }
                let _ = tag;
                ("Types", "type")
            } else {
                return None;
            };
            let entity = if matches!(file_kind_of_uri(&key.uri), FileKind::Def) {
                def_entity_name(path)
            } else {
                None
            };
            let mut items = Vec::new();
            if kind_ctx == "entity" {
                self.push_entity_items(&mut items, &fragment, key.root);
            } else {
                self.push_type_items(&mut items, &fragment);
                self.push_alias_items(&mut items, &fragment);
            }
            Some(CompletionResponse {
                context: CompletionContextFace {
                    kind: "value",
                    section,
                    facet: None,
                    entity,
                    fragment,
                },
                items,
            })
        }
    }

    /// RUST-134: the Python `self.<fragment>` entity-member face (sharing the def
    /// chain queries) — entity
    /// attribution = the py file stem (registration candidates first / in-root
    /// corpus stem as fallback, taking over only on a unique hit; zero or
    /// multiple hits return None and yield to the existing TS chain); properties =
    /// this class's declarations + the inheritance chain (nearer ancestors
    /// first, same-named items shadowed by earlier entries); methods = all three
    /// facets (this class's three-facet declaration order + the inheritance
    /// chain), with facet annotating the owning facet. A case-insensitive prefix
    /// filter on the fragment (the same criteria as the TS python
    /// face); nested `self.a.` multi-segment paths are not taken over (the TS
    /// nested face has different semantics, so they are not mixed); undecidable /
    /// unattributed returns None, with no error and no blocking.
    fn python_self_completion(
        &self,
        key: &DocumentKey,
        prefix: &str,
    ) -> Option<CompletionResponse> {
        let (head, fragment) = prefix.rsplit_once('.')?;
        if !fragment
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_')
        {
            return None;
        }
        let word = head
            .rsplit(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .next()?;
        if word != "self" {
            return None;
        }
        let path = key.uri.as_path();
        let (_, tail) = path.rsplit_once("/scripts/")?;
        let file = tail.rsplit('/').next()?;
        let entity = file.strip_suffix(".py")?;
        if entity.is_empty() {
            return None;
        }
        let def_path = self.corpus_def_for_entity(key.root, entity)?;
        let def = self.corpus_def(def_path.as_str())?;
        let needle = fragment.to_ascii_lowercase();
        let mut items: Vec<CompletionItemFace> = Vec::new();
        let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
        let mut push = |label: String,
                        kind: &'static str,
                        facet: Option<&'static str>,
                        detail: Option<String>,
                        inherited: Option<String>,
                        items: &mut Vec<CompletionItemFace>| {
            if label.to_ascii_lowercase().starts_with(&needle) && seen.insert(label.clone()) {
                items.push(CompletionItemFace {
                    label,
                    kind,
                    facet,
                    detail,
                    inherited_from: inherited,
                });
            }
        };
        for prop in &def.properties {
            push(
                prop.name.clone(),
                "property",
                None,
                prop.type_name.clone(),
                None,
                &mut items,
            );
        }
        for (facet, section) in [
            ("base", MethodSection::Base),
            ("cell", MethodSection::Cell),
            ("client", MethodSection::Client),
        ] {
            for method in def.methods(section) {
                push(
                    method.name.clone(),
                    "method",
                    Some(facet),
                    None,
                    None,
                    &mut items,
                );
            }
        }
        // Inherited members: expanded from the chain face (nearer ancestors first;
        // a missing parent is honestly empty, never fabricated). The chain face is
        // located by def path (defs_root / category probe anchors), not the py path.
        let chain = self.chain_face(&def_path, def);
        for member in &chain.members {
            if !member.exists {
                continue;
            }
            for prop in &member.properties {
                push(
                    prop.name.clone(),
                    "property",
                    None,
                    prop.r#type.clone(),
                    Some(member.entity.clone()),
                    &mut items,
                );
            }
            for method in &member.methods {
                push(
                    method.name.clone(),
                    "method",
                    Some(method.facet),
                    None,
                    Some(member.entity.clone()),
                    &mut items,
                );
            }
        }
        Some(CompletionResponse {
            context: CompletionContextFace {
                kind: "self",
                section: "Entity",
                facet: None,
                entity: Some(entity.to_string()),
                fragment: fragment.to_string(),
            },
            items,
        })
    }

    /// Property/method member face: this class's declarations first (declaration
    /// order), inherited members after (nearer ancestors in the ancestor chain
    /// first, the same chain as hover's inherited-member expansion), with
    /// same-named items shadowed by this class / earlier entries.
    #[allow(clippy::too_many_arguments)]
    fn members_response(
        &self,
        kind: &'static str,
        section: &'static str,
        facet: Option<&'static str>,
        path: &str,
        entity: &str,
        fragment: &str,
        def: &DefFile,
    ) -> CompletionResponse {
        let mut items: Vec<CompletionItemFace> = Vec::new();
        let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
        let mut push = |item: CompletionItemFace, items: &mut Vec<CompletionItemFace>| {
            if item.label.starts_with(fragment) && seen.insert(item.label.clone()) {
                items.push(item);
            }
        };
        if section == "Properties" {
            for prop in &def.properties {
                push(
                    CompletionItemFace {
                        label: prop.name.clone(),
                        kind: "property",
                        facet: None,
                        detail: prop.type_name.clone(),
                        inherited_from: None,
                    },
                    &mut items,
                );
            }
        } else if let Some(facet) = facet {
            for method in def.methods(facet_section(facet)) {
                push(
                    CompletionItemFace {
                        label: method.name.clone(),
                        kind: "method",
                        facet: Some(facet),
                        detail: None,
                        inherited_from: None,
                    },
                    &mut items,
                );
            }
        }
        // Inherited members: expanded from the chain face (nearer ancestors first; a
        // missing parent is honestly empty, never fabricated).
        let chain = self.chain_face(path, def);
        for member in &chain.members {
            if !member.exists {
                continue;
            }
            if section == "Properties" {
                for prop in &member.properties {
                    push(
                        CompletionItemFace {
                            label: prop.name.clone(),
                            kind: "property",
                            facet: None,
                            detail: prop.r#type.clone(),
                            inherited_from: Some(member.entity.clone()),
                        },
                        &mut items,
                    );
                }
            } else if let Some(facet) = facet {
                for method in &member.methods {
                    if method.facet == facet {
                        push(
                            CompletionItemFace {
                                label: method.name.clone(),
                                kind: "method",
                                facet: Some(facet),
                                detail: None,
                                inherited_from: Some(member.entity.clone()),
                            },
                            &mut items,
                        );
                    }
                }
            }
        }
        CompletionResponse {
            context: CompletionContextFace {
                kind,
                section,
                facet,
                entity: Some(entity.to_string()),
                fragment: fragment.to_string(),
            },
            items,
        }
    }

    /// Entity-face items: def corpus registration names (in-root path lexicographic
    /// order; detail = the corpus path;
    /// KBUG-ROOT: only the querying root's candidates are listed).
    fn entities_response(
        &self,
        key: &DocumentKey,
        kind: &'static str,
        section: &'static str,
        fragment: &str,
    ) -> CompletionResponse {
        let mut items = Vec::new();
        self.push_entity_items(&mut items, fragment, key.root);
        CompletionResponse {
            context: CompletionContextFace {
                kind,
                section,
                facet: None,
                entity: None,
                fragment: fragment.to_string(),
            },
            items,
        }
    }

    fn push_entity_items(&self, items: &mut Vec<CompletionItemFace>, fragment: &str, root: RootId) {
        for ((candidate_root, name), paths) in &self.def_by_name {
            if *candidate_root != root {
                continue;
            }
            if name.starts_with(fragment) {
                items.push(CompletionItemFace {
                    label: name.clone(),
                    kind: "entity",
                    facet: None,
                    detail: Some(paths[0].clone()),
                    inherited_from: None,
                });
            }
        }
    }

    /// Type-face items: every corpus types.xml declaration (path order, first seen of a same name).
    fn push_type_items(&self, items: &mut Vec<CompletionItemFace>, fragment: &str) {
        let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
        for file in self.types_files.values() {
            for decl in &file.types {
                if seen.insert(decl.name.clone()) && decl.name.starts_with(fragment) {
                    items.push(CompletionItemFace {
                        label: decl.name.clone(),
                        kind: "type",
                        facet: None,
                        detail: Some(type_kind_str(decl.kind.clone()).to_string()),
                        inherited_from: None,
                    });
                }
            }
        }
    }

    /// Alias-face items: every corpus alias.xml entry (path order, first seen of a same name).
    fn push_alias_items(&self, items: &mut Vec<CompletionItemFace>, fragment: &str) {
        let mut seen: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
        for file in self.alias_files.values() {
            for alias in &file.aliases {
                if seen.insert(alias.name.clone()) && alias.name.starts_with(fragment) {
                    items.push(CompletionItemFace {
                        label: alias.name.clone(),
                        kind: "alias",
                        facet: None,
                        detail: Some(alias.alias_type.clone()),
                        inherited_from: None,
                    });
                }
            }
        }
    }
}

