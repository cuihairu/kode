/// golden file name (repo-relative).
pub const GOLDEN_REL_PATH: &str = "crates/kode-server/tests/golden/completion-parity.json";

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct GoldenScenario {
    line: usize,
    character: u32,
    response: CompletionResponse,
}

#[derive(Debug, Serialize)]
struct GoldenFile {
    file: String,
    kind: String,
    scenarios: Vec<GoldenScenario>,
}

#[derive(Debug, Serialize)]
#[serde(rename_all = "camelCase")]
struct GoldenDump {
    generator: &'static str,
    file_count: usize,
    scenario_count: usize,
    files: Vec<GoldenFile>,
}

/// Scenario point: a 1-based line number + a UTF-16 column.
type ScenarioPos = (usize, u32);

fn utf16_len(s: &str) -> u32 {
    s.chars().map(char::len_utf16).sum::<usize>() as u32
}

/// Scenario enumeration (deterministic; the TS side recomputes the scenarios by
/// the same rules and compares the response point by point):
/// - def: item lines inside the Properties / method / Components sections -> two
///   open-tag points (the full point after `<` + the filtered point at the
///   first 2 chars of the name); `<Parent>` lines and `<Type>`/`<Arg>`/`<of>`
///   lines with a value -> two value points (the full point after the tag + the
///   filtered point at the end of the value's first token);
/// - entities: item lines directly under root -> two open-tag points (same as above).
fn enumerate_scenarios(kind: &str, text: &str) -> Vec<ScenarioPos> {
    let mut out = Vec::new();
    let mut stack: Vec<String> = Vec::new();
    for (idx, line) in text.split('\n').enumerate() {
        let line1 = idx + 1;
        let ws_len = line.len() - line.trim_start().len();
        let ws16 = utf16_len(&line[..ws_len]);
        let trimmed = line.trim_start();
        let top = stack.last().cloned();
        if kind == "def" {
            match top.as_deref() {
                Some("Properties")
                | Some("BaseMethods")
                | Some("CellMethods")
                | Some("ClientMethods")
                | Some("Components") => {
                    if let Some(name) = open_tag_name(trimmed) {
                        // the full point (``+`<`) and the filtered point (first 2 chars of the name).
                        out.push((line1, ws16 + 1));
                        out.push((line1, ws16 + 1 + fragment16(&name)));
                    }
                }
                _ => {}
            }
            let mut value_point = |tag: &str, rest: &str| {
                out.push((line1, ws16 + utf16_len(tag)));
                let value = rest.trim_start();
                if value.is_empty() {
                    return;
                }
                let pad = utf16_len(rest) - utf16_len(value);
                let token = leading_word(value);
                out.push((line1, ws16 + utf16_len(tag) + pad + utf16_len(token)));
            };
            if let Some(rest) = trimmed.strip_prefix("<Parent>") {
                value_point("<Parent>", rest);
            } else if let Some((tag, rest)) = ["<Type>", "<Arg>", "<of>"]
                .iter()
                .find_map(|t| trimmed.strip_prefix(t).map(|rest| (*t, rest)))
            {
                value_point(tag, rest);
            }
        } else if kind == "entities" && top.as_deref() == Some("root") {
            if let Some(name) = open_tag_name(trimmed) {
                out.push((line1, ws16 + 1));
                out.push((line1, ws16 + 1 + fragment16(&name)));
            }
        }
        scan_line_tags(line, &mut stack);
    }
    out
}

/// The value's first token (leading word characters).
fn leading_word(value: &str) -> &str {
    value
        .char_indices()
        .find(|(_, c)| !(c.is_ascii_alphanumeric() || *c == '_'))
        .map(|(i, _)| &value[..i])
        .unwrap_or(value)
}

/// The line-start open-tag name (`^<Name>` or `<Name …>` with attributes; the `</X>`/`<X/>` shapes are not taken).
fn open_tag_name(trimmed: &str) -> Option<String> {
    let rest = trimmed.strip_prefix('<')?;
    let name: String = rest
        .chars()
        .take_while(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '-')
        .collect();
    if name.is_empty() {
        return None;
    }
    let after = &rest[name.len()..];
    if after.starts_with('>') || after.starts_with(char::is_whitespace) {
        Some(name)
    } else {
        None
    }
}

/// The UTF-16 width of the fragment before the name (filter scenarios: at most 2 chars before the name).
fn fragment16(name: &str) -> u32 {
    utf16_len(&name.chars().take(2).collect::<String>())
}

/// The completion golden JSON for the whole corpus (one response per file per scenario point).
pub fn dump_completion_golden(repo_root: &std::path::Path) -> String {
    let files = kode_parser::json::collect_corpus(repo_root, kode_parser::json::PARITY_CORPORA);
    let registry = crate::golden_corpus::corpus_registry();
    let mut engine = HoverEngine::new();
    // Index the full corpus first (lexicographic order = the TS corpus order; keys = each corpus's project root, KBUG-ROOT isolation).
    for (path, (_kind, text)) in &files {
        engine.update(crate::golden_corpus::corpus_key(&registry, path), text);
    }
    let mut dump = GoldenDump {
        generator: "kode-server dump-completion-golden",
        file_count: files.len(),
        scenario_count: 0,
        files: Vec::new(),
    };
    for (path, (kind, text)) in &files {
        let key = crate::golden_corpus::corpus_key(&registry, path);
        let mut scenarios = Vec::new();
        for (line1, character) in enumerate_scenarios(kind, text) {
            if let Some(response) = engine.completion(&key, text, line1 as u32 - 1, character) {
                scenarios.push(GoldenScenario {
                    line: line1,
                    character,
                    response,
                });
            }
        }
        dump.scenario_count += scenarios.len();
        dump.files.push(GoldenFile {
            file: path.clone(),
            kind: kind.to_string(),
            scenarios,
        });
    }
    serde_json::to_string(&dump).expect("serialize completion golden")
}
