/// The line prefix before the cursor on that line (0-based; character counted in UTF-16, past end of line clamps to line end).
fn line_prefix(text: &str, line0: u32, col: usize) -> Option<String> {
    let line = line_text(text, line0)?;
    let mut utf16 = 0usize;
    let mut end = line.len();
    for (idx, ch) in line.char_indices() {
        if utf16 >= col {
            end = idx;
            break;
        }
        utf16 += ch.len_utf16();
    }
    Some(line[..end].to_string())
}

/// The full text of that line (0-based; excluding the line terminator; None when the line is missing).
fn line_text(text: &str, line0: u32) -> Option<&str> {
    if line0 == 0 {
        return text.split('\n').next();
    }
    let mut line = 0u32;
    for (idx, ch) in text.char_indices() {
        if ch == '\n' {
            line += 1;
            if line == line0 {
                let rest = &text[idx + 1..];
                return Some(rest.split('\n').next().unwrap_or(""));
            }
        }
    }
    None
}

/// UTF-16 character -> the in-line char column (0-based; None when the line does not exist).
fn char_col_of(text: &str, line0: u32, character: u32) -> Option<usize> {
    let line = line_text(text, line0)?;
    let mut utf16 = 0u32;
    let mut col = 0usize;
    for ch in line.chars() {
        if utf16 >= character {
            break;
        }
        utf16 += ch.len_utf16() as u32;
        col += 1;
    }
    Some(col)
}

/// Line prefix -> (head with the fragment removed, fragment, whether it is an
/// open tag): the trailing word is the fragment; an immediately preceding `<`
/// makes it an open-tag context (with an empty fragment the prefix ends with
/// `<`).
fn split_fragment(prefix: &str) -> (String, String, bool) {
    let head_end = prefix
        .char_indices()
        .rev()
        .find(|(_, ch)| !(ch.is_ascii_alphanumeric() || *ch == '_'))
        .map(|(idx, _)| idx + prefix[idx..].chars().next().map_or(1, |c| c.len_utf8()))
        .unwrap_or(0);
    let fragment = prefix[head_end..].to_string();
    let head = prefix[..head_end].to_string();
    let open_tag = head.ends_with('<');
    (head, fragment, open_tag)
}

/// All lines above the cursor's line (excluding the current line; used for the
/// stack scan — an item declaration line itself does not nest and affect the
/// stack, the same rule as the TS recomputation).
fn lines_above(text: &str, line0: u32) -> String {
    let mut line = 0u32;
    for (idx, ch) in text.char_indices() {
        if line == line0 {
            return text[..idx].to_string();
        }
        if ch == '\n' {
            line += 1;
        }
    }
    text.to_string()
}

/// Line-level tag stack: accumulates complete tags line by line (`<X>` pushes,
/// `</X>` pops; `<X/>` / `<!--` comments and unclosed trailing tags are
/// ignored). Returns the stack (bottom -> top).
fn tag_stack(above: &str) -> Vec<String> {
    let mut stack: Vec<String> = Vec::new();
    for line in above.split('\n') {
        scan_line_tags(line, &mut stack);
    }
    stack
}

/// Single-line tag scan (advancing the stack; `tag_stack` and the scenario enumeration share the same rule).
fn scan_line_tags(line: &str, stack: &mut Vec<String>) {
    let trimmed = line.trim_start();
    if trimmed.starts_with("<!--") && !trimmed[4..].contains("-->") {
        return;
    }
    let mut i = 0usize;
    while i < line.len() {
        if !line.is_char_boundary(i) {
            i += 1;
            continue;
        }
        if !line[i..].starts_with('<') {
            i += 1;
            continue;
        }
        let Some(rel) = line[i + 1..].find('>') else {
            break; // 未闭合尾标(含跨行标签):忽略
        };
        let inner = &line[i + 1..i + 1 + rel];
        if let Some(name) = inner.strip_prefix('/') {
            if stack.last().map(|t| t == name.trim()).unwrap_or(false) {
                stack.pop();
            }
        } else if !inner.starts_with("!--") && !inner.ends_with('/') {
            let name: String = inner
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '_' || *c == '-')
                .collect();
            if !name.is_empty() {
                stack.push(name);
            }
        }
        i += rel + 2;
    }
}

