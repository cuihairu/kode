// ---------------------------------------------------------------------------
// Response model (structured face; LSP items only project label/kind/detail, not a parity face)
// ---------------------------------------------------------------------------

/// A completion response: the decided context + the ordered item set.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CompletionResponse {
    pub context: CompletionContextFace,
    pub items: Vec<CompletionItemFace>,
}

/// The context face: the decision basis presented in full (same shape on both parity sides).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CompletionContextFace {
    /// "openTag" (line prefix `<fragment`) | "value" (`<Tag> fragment`).
    pub kind: &'static str,
    /// The owning section: Properties/BaseMethods/CellMethods/ClientMethods/Components/
    /// Entity (`<Parent>` value)/Types (`<Type>` and other values)/Entities (directly
    /// under the entities.xml root).
    pub section: &'static str,
    /// The method facet (base/cell/client); None for a non-method face.
    pub facet: Option<&'static str>,
    /// The current def entity name (the def file); None for entities.xml.
    pub entity: Option<String>,
    /// The fragment typed before the cursor (an open tag does not include `<`).
    pub fragment: String,
}

/// A completion item.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct CompletionItemFace {
    pub label: String,
    /// entity | property | method | type | alias (the same literals as the PR-007 symbol kinds).
    pub kind: &'static str,
    /// The method facet.
    pub facet: Option<&'static str>,
    /// Property: the type; type: the kind (fixedDict/array/builtin); alias: what it points to;
    /// entity: the def corpus path.
    pub detail: Option<String>,
    /// Inherited member: the source ancestor entity's name; None for a declaration in this class.
    pub inherited_from: Option<String>,
}

/// LSP items projection (label/kind/detail; CompletionItemKind numeric values):
/// method=2, type/entity/alias=7 (Class), property=10 (Property).
/// RUST-135 additive face (all produced in this projection layer, with zero
/// change to the structured parity face):
/// - sortText: locks the item order (response order = declaration order / chain
///   order, pinned by a zero-padded sequence; once a client has sortText it no
///   longer re-sorts by label lexicographic order);
/// - filterText: an explicit typed filtering face (= label);
/// - insertText/insertTextFormat: method items in the py faces (self/module) are
///   snippets `name($0)` (def XML face tag completions stay plain; the XML
///   mechanism handles the insertion itself);
/// - data: the resolve round-trip payload (the source face is discriminated by
///   context.kind x item.kind).
pub fn to_lsp_items(response: &CompletionResponse, root: RootId) -> Value {
    let items: Vec<Value> = response
        .items
        .iter()
        .enumerate()
        .map(|(seq, item)| {
            let kind = match item.kind {
                "method" => 2,
                "function" => 3,
                "variable" => 6,
                "property" => 10,
                _ => 7,
            };
            let mut obj = serde_json::json!({
                "label": item.label,
                "kind": kind,
                "sortText": format!("{:04}", seq),
                "filterText": item.label,
            });
            if let Some(detail) = &item.detail {
                obj["detail"] = Value::String(detail.clone());
            }
            let snippet = matches!(response.context.kind, "self" | "module")
                && matches!(item.kind, "method" | "function");
            if snippet {
                obj["insertTextFormat"] = Value::from(2);
                obj["insertText"] = Value::from(format!("{}($0)", item.label));
            }
            obj["data"] = resolve_data_face(response, item, root);
            obj
        })
        .collect();
    serde_json::json!({ "isIncomplete": false, "items": items })
}

/// resolve round-trip payload (source-face discrimination): context.kind x item.kind -> source.
/// The payload carries only the deterministic facts resolve needs to recompute
/// (entity attribution / facet / inheritance source / signature);
/// when the corpus is missing, resolve returns the input unchanged without fabricating documentation — never invents anything.
fn resolve_data_face(
    response: &CompletionResponse,
    item: &CompletionItemFace,
    root: RootId,
) -> Value {
    let name = &item.label;
    match (response.context.kind, item.kind) {
        (_, "entity") => serde_json::json!({
            "source": "entity", "name": name, "path": item.detail,
        }),
        (_, "type") => serde_json::json!({
            "source": "type", "name": name, "typeKind": item.detail,
        }),
        (_, "alias") => serde_json::json!({
            "source": "alias", "name": name, "target": item.detail,
        }),
        ("module", _) => serde_json::json!({
            "source": "module", "name": name,
            "process": response.context.facet, "signature": item.detail,
        }),
        (_, "property" | "method") => serde_json::json!({
            "source": "def", "root": root.0, "name": name,
            "entity": response.context.entity,
            "facet": item.facet,
            "inheritedFrom": item.inherited_from,
            "typeKind": item.detail,
        }),
        _ => Value::Null,
    }
}

/// completionItem/resolve lazy detail completion (RUST-135): recomputes the
/// documentation face (type/Flags/signature/facet/source path) from the data
/// payload, zero IO — only touching the indexed corpus views.
/// An undecidable payload / missing corpus / ambiguous attribution -> the input
/// is returned unchanged (no empty documentation is fabricated; the client keeps
/// showing the existing label/detail face).
pub fn resolve_item(engine: &HoverEngine, item: &Value) -> Value {
    let data = item.get("data");
    let label = item.get("label").and_then(Value::as_str);
    let Some(data) = data else {
        return item.clone();
    };
    let Some(label) = label else {
        return item.clone();
    };
    let source = data.get("source").and_then(Value::as_str);
    let documentation = match source {
        Some("entity") => data
            .get("path")
            .and_then(Value::as_str)
            .map(|path| format!("**{label}**\n\n实体声明:`{path}`")),
        Some("type") => data
            .get("typeKind")
            .and_then(Value::as_str)
            .map(|kind| format!("**{label}**\n\n{kind} — types.xml 自定义类型。")),
        Some("alias") => data
            .get("target")
            .and_then(Value::as_str)
            .map(|target| format!("**{label}**\n\n别名指向:`{target}`。")),
        Some("module") => {
            let process = data.get("process").and_then(Value::as_str).unwrap_or("");
            data.get("signature")
                .and_then(Value::as_str)
                .map(|signature| {
                    format!(
                        "**{label}**\n\n```python\n{signature}\n```\n\nKBEngine {process} API。"
                    )
                })
        }
        Some("def") => resolve_def_member_documentation(engine, data, label),
        _ => None,
    };
    let Some(documentation) = documentation else {
        return item.clone();
    };
    let mut resolved = item.clone();
    resolved["documentation"] = serde_json::json!({
        "kind": "markdown",
        "value": documentation,
    });
    resolved
}

/// def member documentation face: entity attribution (root + entity, with
/// inherited members locating the ancestor) -> the corpus def view -> find the
/// property/method declaration by name. Ambiguous attribution / missing corpus
/// -> None.
fn resolve_def_member_documentation(
    engine: &HoverEngine,
    data: &Value,
    label: &str,
) -> Option<String> {
    let root = data.get("root").and_then(Value::as_u64).map(|v| v as u32)?;
    let root = RootId(root);
    let owner = data
        .get("inheritedFrom")
        .and_then(Value::as_str)
        .or_else(|| data.get("entity").and_then(Value::as_str))?;
    let def_path = engine.corpus_def_for_entity(root, owner)?;
    let def = engine.corpus_def(def_path.as_str())?;
    let inherited = data.get("inheritedFrom").and_then(Value::as_str);
    let mut lines = vec![format!("**{label}**")];
    if let Some(prop) = def.properties.iter().find(|p| p.name == label) {
        if let Some(ty) = &prop.type_name {
            lines.push(String::new());
            lines.push(format!("类型:`{ty}`"));
        }
        if let Some(flags) = &prop.flags_raw {
            lines.push(format!("Flags:`{flags}`"));
        }
        if let Some(default) = &prop.default_value {
            lines.push(format!("默认:`{default}`"));
        }
    } else {
        let sections = [
            MethodSection::Base,
            MethodSection::Cell,
            MethodSection::Client,
        ];
        let method = sections.iter().find_map(|section| {
            def.methods(*section)
                .iter()
                .find(|m| m.name == label)
                .map(|m| (*section, m))
        });
        let (section, method) = method?;
        lines.push(String::new());
        lines.push(format!("分面:{}", section.as_str()));
        let mut args = method.args.clone();
        if args.is_empty() {
            args.push("self".to_string());
        }
        let mut signature = format!("{}({})", method.name, args.join(", "));
        if let Some(ret) = &method.return_type {
            signature.push_str(&format!(" -> {ret}"));
        }
        lines.push(format!("```python\n{signature}\n```"));
    }
    if let Some(inherited) = inherited {
        lines.push(String::new());
        lines.push(format!("继承自 {inherited}"));
    }
    lines.push(String::new());
    lines.push(format!("来源:`{def_path}`"));
    Some(lines.join("\n"))
}

// ---------------------------------------------------------------------------
// Engine entry point (mounted on the HoverEngine's corpus views, zero extra state)
