fn type_kind_str(kind: TypeKind) -> &'static str {
    match kind {
        TypeKind::FixedDict => "fixedDict",
        TypeKind::Array => "array",
        TypeKind::Builtin => "builtin",
    }
}

fn facet_of_section(section: &str) -> &'static str {
    match section {
        "BaseMethods" => "base",
        "CellMethods" => "cell",
        _ => "client",
    }
}

