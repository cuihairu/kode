//! completion request path (PR-011, book §8 LSP-005 / §17 PR-011 base version).
//!
//! The "COMP-001..0xx" items mentioned in the task dispatch have no such
//! prefix entries in the book KODE_2_COMPLETE_TODO.md (§8 is the LSP series):
//! this module is implemented per the §17 PR-011 original text + LSP-005, and
//! the chain-face numbering is defined in docs/kode2/pr-011.md and mapped
//! item by item to the book entries, without claiming more than is due.
//!
//! The request path (URI -> position -> context -> item set), all purely
//! synchronous with zero IO (ARCH-012 red line same as hover: it only touches
//! the text this file already holds and the indexed corpus views, with no
//! disk scans):
//! - locating: UTF-16 character -> line prefix (same criteria as the TS line
//!   prefix face);
//! - context: the line-prefix fragment + the full tag stack (line-by-line
//!   scan above the cursor) deciding the face;
//! - the item set (six faces, same source as the PR-007 symbol face /
//!   PR-008 type face): entities (def corpus registration names), properties
//!   (type gray text), method facets (base/cell/client), types (types.xml
//!   declarations), aliases (what alias.xml points to), inherited members
//!   (def-chain ancestors' properties/methods, with inheritedFrom explicitly
//!   annotated; a same-named item shadowed by this class / an earlier item is
//!   not emitted twice).
//!
//! The face-decision rules (item-by-item matching the TS dual-track parity, see
//! tests/kodeCompletionParity.test.ts):
//! - open-tag context: the line prefix ends with `<fragment` and the top of
//!   the tag stack above the cursor is
//!   `Properties` -> the property face; `Base/Cell/ClientMethods` -> the
//!   method face (this facet only); `Components` -> the entity face (the
//!   component type is the def name); the `root` top of entities.xml -> the
//!   entity face; any other stack top (interface section / property sub-tags /
//!   def top level) does not take over -> None;
//! - value context: the line prefix is `<Parent>` followed by whitespace +
//!   fragment -> the entity face;
//!   `<Type>`/`<Arg>`/`<of>` followed by whitespace + fragment -> the type
//!   face + the alias face (the TS `<(Type|Arg|of)>` trigger face uses the
//!   same criteria);
//! - filtering: a case-sensitive startsWith on the fragment (determinism
//!   first, same rule on both tracks);
//! - type face / alias face dedup: the first-seen of a same name is kept
//!   (corpus-path lexicographic order = first write wins).
//!
//! Parity: the TS side `tests/kodeCompletionParity.test.ts` independently
//! recomputes the completion surface of the same corpus with the existing
//! defParser/defChain primitives and compares field by field with the golden
//! generated by [`dump_completion_golden`] (two-way gate, isomorphic with
//! PR-005/007/008/010).
//! Cutover: not done in this order — the TS provider keeps its existing chain,
//! with no default switch (after the PR-012 gate).

